// Geolocation based language detection
async function autoDetectLanguage() {
  // If user has explicitly selected a language, skip auto-detection
  if (localStorage.getItem('upi_split_lang_pref')) {
    document.getElementById('lang-select').value = currentLang;
    updateText();
    return;
  }
  
  try {
    const res = await fetch('https://ipapi.co/json/');
    const data = await res.json();
    if (data.country_code === 'IN') {
      const region = data.region;
      if (region === 'Maharashtra') currentLang = 'mr';
      else if (region === 'West Bengal') currentLang = 'bn';
      else if (region === 'Tamil Nadu') currentLang = 'ta';
      else if (region === 'Andhra Pradesh' || region === 'Telangana') currentLang = 'te';
      else if (region === 'Gujarat') currentLang = 'gu';
      else currentLang = 'hi'; // Default Hindi for North/Central India
    }
  } catch (err) {
    console.error('GeoIP fetch failed', err);
  }
  document.getElementById('lang-select').value = currentLang;
  updateText();
}
autoDetectLanguage();

