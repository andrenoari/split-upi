document.getElementById('btn-share-receipt').addEventListener('click', async () => {
  const shareBtn = document.getElementById('btn-share-receipt');
  const originalHtml = shareBtn.innerHTML;
  
  shareBtn.innerHTML = '<i data-lucide="loader" style="margin-right: 8px;"></i><span>Loading...</span>';
  lucide.createIcons();
  
  try {
    const receiptCard = document.getElementById('done-receipt-card');
    
    // Slight delay to ensure DOM layout is complete
    await new Promise(r => setTimeout(r, 100));
    
    const canvas = await html2canvas(receiptCard, { 
      scale: 3, // Higher resolution
      backgroundColor: '#ffffff',
      useCORS: true,
      logging: false
    });
    
    canvas.toBlob(async (blob) => {
      // JPEG is much more likely to be treated as a photo by WhatsApp than PNG
      const file = new File([blob], 'payment_receipt.jpg', { type: 'image/jpeg' });
      const text = `I just paid ₹${(state.totalPaise / 100).toFixed(2)} to ${state.name || state.vpa} split across ${state.chunks.length} transactions.\n\nSent via Smart UPI Splitter.`;
      
      if (navigator.canShare && navigator.canShare({ files: [file] })) {
        try {
          // WhatsApp and some other apps often drop the `text` payload when a file is attached via Web Share.
          // Copying it to the clipboard ensures the user can just hit "Paste" in the caption box!
          try { await navigator.clipboard.writeText(text); } catch(err){}
          
          await navigator.share({
            text: text,
            files: [file]
          });
        } catch (e) {
          console.log('Error sharing:', e);
        }
      } else {
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = 'payment_receipt.jpg';
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
        
        try { await navigator.clipboard.writeText(text); } catch(err){}
      }
      
      shareBtn.innerHTML = originalHtml;
      lucide.createIcons();
    }, 'image/jpeg', 0.95);
    
  } catch (err) {
    console.error("Error generating receipt image", err);
    shareBtn.innerHTML = originalHtml;
    lucide.createIcons();
    alert("Could not generate image receipt.");
  }
});

