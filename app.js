const inrFormat = new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', minimumFractionDigits: 2 });
const inrFormatNoDec = new Intl.NumberFormat('en-IN', { style: 'currency', currency: 'INR', minimumFractionDigits: 0, maximumFractionDigits: 0 });

function formatPaise(paise) {
  if (paise % 100 === 0) return inrFormatNoDec.format(paise / 100);
  return inrFormat.format(paise / 100);
}

function calculateMDR(totalPaise) {
  if (totalPaise <= 200000) return 0;
  return Math.min(Math.round(totalPaise * 0.004), 30000);
}

function splitAmount(totalPaise, capPaise) {
  const n = Math.max(1, Math.ceil(totalPaise / capPaise));
  if (n === 1) return [totalPaise];
  const base = Math.floor(totalPaise / n / 100) * 100;
  const rem = totalPaise - base * n;
  const extraRupees = Math.floor(rem / 100);
  const paise = rem % 100;
  return Array.from({ length: n }, (_, i) =>
    base + (i < extraRupees ? 100 : 0) + (i === n - 1 ? paise : 0)
  );
}

function generateUpiLink(vpa, name, paise, note) {
  const p = new URLSearchParams({ pa: vpa, am: (paise / 100).toFixed(2), cu: 'INR' });
  if (name) p.set('pn', name);
  if (note) p.set('tn', note);
  return 'upi://pay?' + p.toString();
}

