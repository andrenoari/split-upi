function onScanSuccess(decodedText, decodedResult) {
  if (decodedText.toLowerCase().startsWith('upi://')) {
    try {
      const fakeUrl = decodedText.replace(/^upi:\/\//i, 'http://');
      const url = new URL(fakeUrl);
      state.vpa = url.searchParams.get('pa') || '';
      let pn = url.searchParams.get('pn') || '';
      if (pn) state.name = decodeURIComponent(pn.replace(/\+/g, ' '));
      
      let am = url.searchParams.get('am');
      if (am) {
        state.totalPaise = Math.round(parseFloat(am) * 100);
      }
      
      document.getElementById('btn-close-modal').click();
      initScreenAmount(false);
    } catch(e) { console.error(e); }
  } else if (decodedText.includes('@')) {
    state.vpa = decodedText;
    state.name = '';
    document.getElementById('btn-close-modal').click();
    initScreenAmount(false);
  }
}

