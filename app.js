function saveTransaction() {
  const history = JSON.parse(localStorage.getItem('upi_split_history') || '[]');
  const txn = {
    id: Date.now().toString(),
    date: new Date().toISOString(),
    name: state.name || state.vpa || 'Merchant',
    vpa: state.vpa || '',
    totalPaise: state.totalPaise,
    chunks: state.chunks // Save array instead of length for detail view
  };
  history.unshift(txn); // Add to top
  localStorage.setItem('upi_split_history', JSON.stringify(history));
}

function renderHistory() {
  const container = document.getElementById('history-list-container');
  container.innerHTML = '';
  
  const history = JSON.parse(localStorage.getItem('upi_split_history') || '[]');
  const t = translations[currentLang] || translations['en'];
  
  if (history.length === 0) {
    container.innerHTML = `
      <div class="empty-state">
        <i data-lucide="receipt"></i>
        <div>${t.historyEmpty || 'No past payments yet.'}</div>
      </div>
    `;
    lucide.createIcons();
    return;
  }
  
  history.forEach(txn => {
    const d = new Date(txn.date);
    const dateStr = d.toLocaleDateString(undefined, { month: 'short', day: 'numeric', year: 'numeric' });
    const chunksCount = Array.isArray(txn.chunks) ? txn.chunks.length : txn.chunks;
    
    const div = document.createElement('div');
    div.className = 'history-item';
    div.style.cursor = 'pointer';
    
    const initial = txn.name.charAt(0).toUpperCase();
    
    div.innerHTML = `
      <div class="history-icon">${initial}</div>
      <div class="history-details">
        <div class="history-name">
          <span>${txn.name}</span>
          <span>${formatPaise(txn.totalPaise)}</span>
        </div>
        <div class="history-date">${dateStr}</div>
        <div class="history-badge">${t.historySplit || 'Split in'} ${chunksCount}</div>
      </div>
    `;
    
    div.addEventListener('click', () => {
      showHistoryDetails(txn);
    });
    
    container.appendChild(div);
  });
}

