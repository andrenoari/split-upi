function startCamera() {
  if (!html5QrCode) {
    html5QrCode = new Html5Qrcode("qr-reader");
  }
  
  Html5Qrcode.getCameras().then(devices => {
    if (devices && devices.length) {
      let cameraId = devices[devices.length - 1].id;
      html5QrCode.start(
        cameraId, 
        { fps: 10, qrbox: { width: 250, height: 250 } },
        (decodedText, decodedResult) => {
           html5QrCode.stop().then(() => {
             isScanning = false;
             onScanSuccess(decodedText, decodedResult);
           }).catch(console.error);
        },
        (errorMessage) => { /* ignore */ }
      ).then(() => {
        isScanning = true;
      }).catch(err => {
        showCameraError("Could not start camera. Please check permissions.");
      });
    } else {
      showCameraError("No camera found on this device.");
    }
  }).catch(err => {
    showCameraError("Error accessing camera. Are permissions granted?");
  });
}

